<?php

header("Access-Control-Allow-Origin: https://localhost.akuprof.ru");
header("Access-Control-Allow-Credentials: true");
header("Access-Control-Allow-Methods: GET, POST, OPTIONS");
header("Access-Control-Allow-Headers: Content-Type, Authorization");

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(200);
    exit();
}


require __DIR__ . '/../../vendor/autoload.php';
require_once 'functions.php';

use GuzzleHttp\Client;

$client = generatClient("client");

if($_SERVER['REQUEST_METHOD'] === 'POST'){

    $input = file_get_contents('php://input');

    $data = json_decode($input, true);

    $story = $data['story'];
    $request = $data['request'];

    $prompt = '
        Ты анализируешь диалог между пользователем и ассистентом.

        Твоя задача — определить, зависит ли текущий вопрос от предыдущего диалога.

        ВАЖНО:
        Ты должен быть ОЧЕНЬ СТРОГИМ.
        Если нет явных признаков зависимости — считай вопрос самостоятельным.

        ---

        Считай, что вопрос относится к прошлому диалогу ТОЛЬКО если:

        1. Есть местоимения или ссылки:
        "этот", "тот", "его", "этого", "предыдущий",
        "из списка", "первый", "второй", "они", "их"

        2. Вопрос явно продолжает прошлую мысль:
        например:
        "а как его крепить?"
        "подойдет ли он?"
        "сколько нужно?"
        "есть ли он в наличии?"

        ---

        Считай вопрос ПОЛНОСТЬЮ САМОСТОЯТЕЛЬНЫМ, если:

        1. В вопросе есть новая задача или новый объект
        (например: "нужна шумоизоляция для стены в ванной")

        2. Вопрос можно понять БЕЗ истории диалога

        3. Нет местоимений и ссылок на прошлое

        4. Вопрос вводит НОВЫЕ условия
        (другая комната, другая задача, другой тип товара)

        5. Если вопрос про общую информацию
            (доставка, самовывоз, контакты, способы оплаты)
            и нет явной привязки, к какому либо товару или объекту,
            пример: можно ли при получении оплатить по карте;
            то в этом случаи, НЕ переделывай вопрос, оставь его как есть

        6. Если вопрос начинается с приветствия
            ("здравствуйте", "добрый день" и т.д.)
            — НЕ переделывай его

        - В этих случаях:

        * НЕ используй информацию из прошлого диалога
        * НЕ подставляй товары
        * НЕ добавляй ничего от себя
        * Верни вопрос как есть

        ---

        Если вопрос относится к прошлому диалогу:

        Перепиши последний вопрос пользователя так,
        чтобы он был полностью понятен без истории диалога.

        ---

        Дополнительные правила:

        1. Если вопрос уже самостоятельный — верни его без изменений

        2. Если пользователь задаёт короткий вопрос
        ("пришли ссылку", "сколько стоит", "есть в наличии",
        "подойдет ли", "какая толщина", "покажи фото")
        — считай, что он относится к последнему товару

        3. Замени местоимения:
        "этот", "тот", "его", "этого", "предыдущий",
        "из списка", "первый", "второй"
        → на конкретное название товара из диалога

        4. Если вопрос начинается с приветствия
        ("здравствуйте", "добрый день" и т.д.)
        — НЕ переделывай его

        5. Если вопрос про общую информацию
        (доставка, самовывоз, контакты, способы оплаты)
        и нет привязки к товару — НЕ переделывай

        6. Не придумывай товары, если их нет в вопросе

        7. Не добавляй бренды или модели от себя

        8. Не расширяй вопрос

        9. Делай максимально коротко

        ---

        Верни только итоговый вопрос.

    ';

    $response = reviewGpt($client, $prompt, $story, $request);

    echo json_encode([
        "response" => $response
    ]);
}

function reviewGpt(Client $client, $prompt, $story, $request){
    $response = $client->post(
        'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=' . GEMINI_API_KEY,
        [
            'headers' => [
                'Content-Type' => 'application/json',
            ],
            'json' => [
                'systemInstruction' => [
                    'parts' => [
                        [
                            'text' => $prompt
                        ]
                    ]
                ],
                'contents' => [
                    [
                        'parts' => [
                            [
                                'text' => "История диалога:\n$story\n\nТекущий вопрос:\n$request"
                            ]
                        ]
                    ]
                ]
            ]
        ]
    );

    $data = json_decode($response->getBody(), true);

    return $data['candidates'][0]['content']['parts'][0]['text'] ?? '';
}